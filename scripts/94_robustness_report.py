"""Write reports/ROBUSTNESS_STAGE2.md from results/a2/robustness/ (R1-R4), applying the
interpretation rules of docs/STAGE2_ROBUSTNESS_PLAN.md section 3a mechanically. Every number is
read from a results file; the rule outcomes are computed here, on test, with validation beside.

  python scripts/94_robustness_report.py
"""
from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
R = REPO / "results" / "a2" / "robustness"
OUT = REPO / "reports" / "ROBUSTNESS_STAGE2.md"

WORDING_ZS = ("passes the pre-registered rule on test for one of five sources (string) with a CI "
              "bound at −0.0001; the rule has no correction across sources; the same source "
              "fails on validation. We do not claim zero-shot transfer.")
WORDING_PLAN = ("fails on validation and test; planning is not distinguishable from kNN-imputed "
                "retrieval.")


def load(rel):
    return json.loads((R / rel).read_text())


def p(x):
    return "–" if x is None else f"{x:.2g}" if x < 0.001 else f"{x:.3f}"


def pct(x):
    return "–" if x is None else f"{100 * x:+.2f}%"


def num(x, nd=4):
    return "–" if x is None else f"{x:.{nd}f}"


def holds(t) -> bool:
    return bool(t.get("p_one_sided") is not None and t["p_one_sided"] < 0.05 and t["mean"] < 0)


def row(name, t):
    return (f"| {name} | {t.get('n_groups', '–')} | {num(t.get('model'))} | "
            f"{num(t.get('baseline'))} | {pct(t.get('relative_change'))} | "
            f"{num(t.get('mean'), 5)} | {p(t.get('p_one_sided'))} |")


HEAD = ("| comparison (first − second) | plates | first | second | relative | mean diff | "
        "p (one-sided) |\n|---|---|---|---|---|---|---|")


def outcomes(s: dict) -> dict:
    """I1, I2, I3 for one split's results (s = {'r1':..., 'r2':..., 'r3':...})."""
    t1 = s["r1"]["tests"]["real_vs_trained_shuffled"]
    lam = s["r2"]["lambda_validation"]
    t2 = s["r2"]["tests"][f"real_vs_R2_lambda_{lam}"]
    a = s["r3"]["a_token_zeroed"]
    i1 = holds(t1)
    i2c = holds(t2)
    i3c = bool(a["fraction_of_gain_retained"] >= 0.5 and holds(a["vs_selected_agnostic"]))
    return {"I1": i1, "I2": i1 and i2c, "I2_component": i2c, "I3": i1 and i3c,
            "I3_component": i3c, "t1": t1, "t2": t2, "lam": lam, "a": a}


def claim(o: dict) -> list[str]:
    """Section 3a wording, selected mechanically by the test outcomes."""
    out = []
    if not o["I1"]:
        out.append("**I1 fails.** The G-Signal-2 pass is reported as recorded, together with "
                   "the statement that a trained-shuffled control matches it. No "
                   "gene-conditioning claim is made, and the paper is a negative result.")
    elif not o["I2"]:
        out.append("**I1 holds, I2 fails.** The action input carries gene information; the "
                   "claim is \"gene-conditioned forecasts, equivalent to an additive per-reagent "
                   "correction\".")
    else:
        out.append("**I1 and I2 hold.** The action input carries gene information, and the "
                   "forecasts go beyond additive memorisation (gene × state).")
    if o["I3"]:
        out.append("**I3 holds:** with the siRNA token zeroed, the gain over agnostic keeps "
                   f"{100 * o['a']['fraction_of_gain_retained']:.0f}% of its size and stays "
                   "p < 0.05; the gain is gene-level rather than reagent-level.")
    else:
        comp = (f"with the siRNA token zeroed the gain over agnostic keeps "
                f"{100 * o['a']['fraction_of_gain_retained']:.0f}% of its size (p = "
                f"{p(o['a']['vs_selected_agnostic']['p_one_sided'])}), so the R3(a) part "
                f"{'would hold' if o['I3_component'] else 'also fails'}")
        why = f"I1 fails; {comp}" if not o["I1"] else comp
        out.append(f"**I3 fails** ({why}); the gain is not shown to be gene-level rather than "
                   "reagent-level, and the screenB result (independent siRNAs, token masked) "
                   "is the explanation.")
    return out


def main() -> int:
    S = {sp: {k: load(f"{k}/{k}_{sp}.json") for k in ("r1", "r2", "r3", "r4")}
         for sp in ("val", "test")}
    O = {sp: outcomes(S[sp]) for sp in S}
    L = ["# Stage 2: robustness controls (post hoc, exploratory, after the test)", "",
         "Generated by `scripts/94_robustness_report.py` from `results/a2/robustness/`. The "
         "controls and their interpretation rules are fixed in `docs/STAGE2_ROBUSTNESS_PLAN.md` "
         f"(commit `{S['test']['r1']['plan_commit']}`), committed before any of them ran. "
         "**Every number here is exploratory, after the test.** The pre-registered results "
         "stand as recorded in `results/a2/gates_val.json` and `results/a2/gates_test.json`.", "",
         "Statistic throughout: primary wells, mean error at 24 h and 36 h, errors averaged "
         "over 3 seeds, per-plate means, one-sided Monte Carlo sign flip over plates "
         "(100,000 draws). A negative mean difference means the first-named model has lower "
         "error. Each results file first recomputes the real model's comparison with the "
         "selected agnostic models and checks it against the recorded `results/a2/h1` file "
         "(all checks matched).", "",
         "## Interpretation rules (section 3a), applied mechanically", "",
         "| rule | test | validation (beside) | deciding numbers (test) |", "|---|---|---|---|"]
    for k, desc in (("I1", "real `h1_learned` beats the R1 trained-shuffled model, p < 0.05"),
                    ("I2", "I1, and real beats R2 at the validation-chosen λ, p < 0.05"),
                    ("I3", "I1, and under R3(a) the gain keeps ≥ 50% and stays p < 0.05")):
        o, v = O["test"], O["val"]
        if k == "I1":
            d = (f"real − shuffled {num(o['t1']['mean'], 5)} ({pct(o['t1']['relative_change'])}), "
                 f"p = {p(o['t1']['p_one_sided'])}")
        elif k == "I2":
            d = (f"λ = {o['lam']:g}; real − R2 {num(o['t2']['mean'], 5)} "
                 f"({pct(o['t2']['relative_change'])}), p = {p(o['t2']['p_one_sided'])}")
        else:
            d = (f"retained {100 * o['a']['fraction_of_gain_retained']:.1f}%; token-zeroed − "
                 f"agnostic p = {p(o['a']['vs_selected_agnostic']['p_one_sided'])}")
        L.append(f"| **{k}**: {desc} | **{'holds' if o[k] else 'does not hold'}** | "
                 f"{'holds' if v[k] else 'does not hold'} | {d} |")
    L += ["", "## What the paper can claim (section 3a wording)", ""] + [x for c in claim(O["test"]) for x in (c, "")] + [
        "", "Fixed wording (section 4), whatever R1–R4 show:", "",
        f"- **G-ZeroShot-2:** \"{WORDING_ZS}\"",
        f"- **G-Plan-2:** \"{WORDING_PLAN}\"",
        "- **ScreenB:** reported in the main text, not only in the supplement.", ""]
    for sp in ("test", "val"):
        r1, r2, r3, r4 = (S[sp][k] for k in ("r1", "r2", "r3", "r4"))
        L += [f"## {'Test' if sp == 'test' else 'Validation'} ({r1['n_wells_primary']} primary "
              f"wells, {r1['n_plates_primary']} plates)", "",
              "### R1: trained-shuffled H1 control (P1)", "",
              f"Trained-shuffled `h1_learned` and config-matched `h1_none`, both at "
              f"`{r1['trained_shuffled']['config']}`, 3 seeds; permutation SHA-256 per seed: "
              + ", ".join(f"s{k}: `{v['sha256'][:16]}`" for k, v in
                          sorted(r1["trained_shuffled"]["permutations"].items())) + ".", "",
              HEAD]
        L += [row(k.replace("_", " "), t) for k, t in r1["tests"].items()]
        f = r1["fraction_of_gain_over_selected_agnostic_reached_by_trained_shuffled"]
        L += ["", f"The trained-shuffled model reaches {100 * f:.1f}% of the real model's gain "
              "over the selected agnostic models.", "",
              "### R2: additive memorisation baseline (P2)", "",
              f"λ chosen on validation: **{r2['lambda_validation']:g}** (grid "
              f"{', '.join(f'{x:g}' for x in r2['lambda_grid'])}). Residual sources: "
              f"`{json.dumps(r2['residual_sources'])}`. Caveat: {r2['caveat']}.", "", HEAD]
        L += [row(k.replace("_", " "), t) for k, t in r2["tests"].items()]
        L += ["", "Phenotype probe at 36 h on R2's forecasts (AUROC, 95% cluster-bootstrap CI "
              "over plates):", "",
              "| class | action-conditioned | R2 (λ val) | agnostic | AC − R2 | R2 − agnostic |",
              "|---|---|---|---|---|---|"]
        for c, v in r2["phenotype_probe_36h"].items():
            if not v or "auroc" not in v:
                L.append(f"| {c} | skipped | | | | |")
                continue
            a, d = v["auroc"], v["difference"]

            def ci(x):
                return f"{x['value']:.3f} [{x['ci95'][0]:.3f}, {x['ci95'][1]:.3f}]"
            L.append(f"| {c} | {ci(a['action_conditioned'])} | {ci(a['R2_lambda_validation'])} "
                     f"| {ci(a['action_agnostic'])} "
                     f"| {ci(d['action_conditioned-R2_lambda_validation'])} "
                     f"| {ci(d['R2_lambda_validation-action_agnostic'])} |")
        a, b, cg = (r3["a_token_zeroed"], r3["b_labels_permuted_within_plate"],
                    r3["c_global_token_zeroed"])
        L += ["", "### R3: reagent dependence (P3)", "", HEAD,
              row("real (full) vs selected agnostic", r3["full_gain_vs_selected_agnostic"]),
              row("(a) token zeroed vs selected agnostic", a["vs_selected_agnostic"]),
              row("real vs (a) token zeroed", a["real_vs_token_zeroed"]),
              row("(b) labels permuted within plate vs selected agnostic",
                  b["vs_selected_agnostic"]),
              row("real vs (b) labels permuted", b["real_vs_permuted"]),
              row("global: real vs selected agnostic", cg["full_gain_vs_selected_agnostic"]),
              row("(c) global, token zeroed vs selected agnostic", cg["vs_selected_agnostic"]),
              "", f"Fraction of the gain over agnostic retained: (a) "
              f"{100 * a['fraction_of_gain_retained']:.1f}%, (c) global "
              f"{100 * cg['fraction_of_gain_retained']:.1f}%.", "",
              "### R4: where the gain sits (descriptive; real vs selected agnostic)", "", HEAD]
        L += [row(f"primary, {h}", t) for h, t in r4["per_horizon_primary"].items()]
        L += [row(f"primary, training-plate class {c}", t) if "skipped" not in t else
              f"| primary, training-plate class {c} | {t['n_wells']} wells: skipped "
              f"({t['skipped']}) | | | | | |"
              for c, t in r4["per_training_plate_class_primary"].items()]
        L += [row("non-primary library wells, 24/36 h", r4["non_primary_library_wells"]),
              row("primary wells, 24/36 h", r4["primary_wells"]), ""]
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT.relative_to(REPO)}")
    print(json.dumps({sp: {k: O[sp][k] for k in ("I1", "I2", "I3")} for sp in O}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
